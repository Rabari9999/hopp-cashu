// The web client (ADR 0022) only on request: -Phopp.web=true. Without it no build
// sees the wasmJs target — not the apps', not F-Droid's recipe nor its scanner
// (Node, Yarn and npm packages come in with the target).
val hoppWeb = providers.gradleProperty("hopp.web").map { it.toBoolean() }.getOrElse(false)
// The web client's version: the apps' (androidApp/build.gradle.kts, appVersion).
val webVersionDir = layout.buildDirectory.dir("generated/hopp/wasmJsMain/kotlin")
val generateWebVersion = tasks.register("generateWebVersion") {
    val gradleFile = rootProject.layout.projectDirectory.file("androidApp/build.gradle.kts")
    val dir = webVersionDir
    inputs.file(gradleFile)
    outputs.dir(dir)
    doLast {
        val version = Regex("val appVersion = \"([^\"]+)\"").find(gradleFile.asFile.readText())?.groupValues?.get(1) ?: "0.0.0"
        val out = dir.get().file("space/sovereigncast/hopp/WebVersion.kt").asFile
        out.parentFile.mkdirs()
        out.writeText("package space.sovereigncast.hopp\n\n// Generated by shared/build.gradle.kts.\ninternal object WebVersion {\n    const val NAME = \"$version\"\n}\n")
    }
}
val generateDistribution = tasks.register("generateDistribution") {
    val distribution = hoppDistribution
    val dir = distributionDir
    inputs.property("distribution", distribution)
    outputs.dir(dir)
    doLast {
        val appStore = distribution.get() == "appstore"
        val out = dir.get().file("space/sovereigncast/hopp/Distribution.kt").asFile
        out.parentFile.mkdirs()
        out.writeText(
            "package space.sovereigncast.hopp\n\n" +
                "// Generated by shared/build.gradle.kts. Fixed at build time (ADR 0009) — not a remote flag.\n" +
                "internal object Distribution {\n" +
                "    const val appStore: Boolean = $appStore\n" +
                "}\n",
        )
    }
}
